"""
服务层 · 写手后处理
===================
写手交稿之后的两道补救题：

    主权纠错   —— 上一稿替玩家做了决定，要求重写
    选项补全   —— 正文末尾没有可识别的行动参考，单独补一组

两者都是「模型没按契约交货时的兜底」，不是常规流程。它们的提示词和写手契约
描述的是同一套边界（谁能替玩家行动、选项该长什么样），所以放在后端和
prompt_builder 做邻居，改的时候看得见彼此。

注意这里只搬提示词。解析与拼装留在前端：判断「正文有没有选项」用的是同一个
解析器，前端本来就需要它（主权检测也要用），搬过去等于两边各存一份。
"""

REWRITE_MAX_TOKENS = 4096
OPTION_MAX_TOKENS = 260
OPTION_TEMPERATURE = 0.35


def build_agency_guard(codes: list[str]) -> str:
    """
    要求写手重写越权的那一稿。

    作为 system 消息追加在原始对话之后，所以只说「要改什么」，
    不重复世界设定——那些在原始 system prompt 里已经有了。
    """
    return (
        "【玩家主权纠错——重写上一稿】上一稿出现以下越权："
        + "、".join(str(c) for c in (codes or []))
        + "。玩家本回合只授权了原输入明确表达的动作。请完整重写上一稿："
        "保留世界对玩家输入的直接反馈与必要环境变化，"
        "删除所有玩家未明确做出的点击、发送、说话、接受、拒绝、决定、移动、使用或调查；"
        "在出现新选择之前停下。不得在正文提及纠错、上一稿或系统。"
        "仍需提供2-4个眼前行动参考和自由输入；隐藏状态块只保留真正发生的变化。"
    )


def build_option_repair(*, draft: str, player_input: str) -> str:
    """
    正文没给出行动参考时，单独补一组。

    「至少包含一个低承诺或暂不推进的选择」这条是刻意的：
    选项全是推进剧情的动作，等于把「什么也不做」这个合法选择从桌上拿走了。
    """
    visible = strip_hidden_blocks(draft)[-4500:]
    return (
        "你是互动小说的行动选项编辑器，不写或改动小说正文。"
        "根据已经发生的可见场景，提取2-4个玩家此刻立刻能做、彼此真正不同的行动。"
        "不得新增人物、地点、物品、秘密、任务或尚未出现的信息；不得替玩家选定长期目标。"
        "至少包含一个低承诺或暂不推进的选择。"
        '只输出JSON：{"options":["完整行动1","完整行动2"]}。\n'
        "玩家上一条输入：" + str(player_input or "")[:1200] + "\n可见场景：\n" + visible
    )


def strip_hidden_blocks(text: str) -> str:
    """只留玩家看得见的正文——隐藏协议块对这两道题都没用。"""
    import re

    out = str(text or "")
    return re.sub(
        r"【(?:STATE|SHEET_INIT|大纲|命名表|裁定)】[\s\S]*?"
        r"(?:【/(?:STATE|SHEET_INIT|大纲|命名表|裁定)】|$)",
        "", out,
    ).strip()

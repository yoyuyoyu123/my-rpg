function unique(values) {
  return [...new Set(values)];
}

function buildRecord(rawTag, frequency) {
  if (canonical.has(rawTag)) {
    return {
      raw_tag: rawTag,
      frequency,
      canonical_tags: [rawTag],
      action: 'existing',
      rationale: '与 tag_ontology.json 中的现有标签完全一致。'
    };
  }

  if (forcedKeepRaw.has(rawTag)) {
    return {
      raw_tag: rawTag,
      frequency,
      canonical_tags: [],
      action: 'keep_raw',
      rationale: forcedKeepRaw.get(rawTag)
    };
  }

  if (candidate.has(rawTag)) {
    const item = candidate.get(rawTag);
    return {
      raw_tag: rawTag,
      frequency,
      canonical_tags: item.canonicalTags,
      action: 'new_candidate',
      rationale: item.rationale
    };
  }

  if (exactAlias.has(rawTag)) {
    const item = exactAlias.get(rawTag);
    return {
      raw_tag: rawTag,
      frequency,
      canonical_tags: item.canonicalTags,
      action: 'alias',
      rationale: item.rationale
    };
  }

  const matched = regexRules.filter((item) => item.pattern.test(rawTag));
  if (matched.length) {
    return {
      raw_tag: rawTag,
      frequency,
      canonical_tags: unique(matched.flatMap((item) => item.canonicalTags)),
      action: 'alias',
      rationale: unique(matched.map((item) => item.rationale)).join(' ')
    };
  }

  return {
    raw_tag: rawTag,
    frequency,
    canonical_tags: [],
    action: 'keep_raw',
    rationale: frequency > 1
      ? '概念重复出现，但当前语义仍过宽或上下文依赖强；先保留原始标签，待人工审阅后再决定是否升格。'
      : '低频且高度具体的角色、场景或情节描述；保留用于作品检索，不提升为通用本体。'
  };
}

const records = [...counts.entries()]
  .map(([rawTag, frequency]) => buildRecord(rawTag, frequency))
  .sort((a, b) => b.frequency - a.frequency || a.raw_tag.localeCompare(b.raw_tag, 'zh-Hans-CN'));

for (const record of records) {
  if (!['existing', 'alias', 'new_candidate', 'keep_raw'].includes(record.action)) {
    throw new Error(`Invalid action for ${record.raw_tag}`);
  }
  if ((record.action === 'existing' || record.action === 'alias') &&
      record.canonical_tags.some((tag) => !canonical.has(tag))) {
    throw new Error(`Unknown canonical tag for ${record.raw_tag}: ${record.canonical_tags.join(', ')}`);
  }
  if (record.action === 'keep_raw' && record.canonical_tags.length) {
    throw new Error(`keep_raw must not contain canonical tags: ${record.raw_tag}`);
  }
}


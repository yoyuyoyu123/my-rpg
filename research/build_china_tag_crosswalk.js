const fs = require('fs');
const path = require('path');

const researchDir = __dirname;
const sourceFiles = fs.readdirSync(researchDir)
  .filter((name) => /^china_works.*\.json$/.test(name))
  .sort();
const works = sourceFiles.flatMap((name) =>
  JSON.parse(fs.readFileSync(path.join(researchDir, name), 'utf8'))
);
const ontology = JSON.parse(
  fs.readFileSync(path.join(researchDir, 'tag_ontology.json'), 'utf8')
);

const canonical = new Set(
  ontology.categories.flatMap((category) => category.tags)
);
const frequency = new Map();
for (const work of works) {
  for (const rawTag of work.tags || []) {
    frequency.set(rawTag, (frequency.get(rawTag) || 0) + 1);
  }
}

const manual = new Map();

function register(action, rawTags, canonicalTags, rationale) {
  for (const rawTag of rawTags) {
    if (manual.has(rawTag)) {
      throw new Error(`Duplicate manual mapping: ${rawTag}`);
    }
    manual.set(rawTag, { action, canonical_tags: canonicalTags, rationale });
  }
}

function alias(rawTags, canonicalTags, rationale) {
  register('alias', rawTags, canonicalTags, rationale);
}

function candidate(rawTags, canonicalTags, rationale) {
  register('new_candidate', rawTags, canonicalTags, rationale);
}

